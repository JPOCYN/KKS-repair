-- KKS Repair keeps its server-rendered application as the only database client.
-- Browser roles receive no table privileges; the backend uses a Supabase secret
-- key, which maps to service_role. RLS is still enabled on every exposed table.

create extension if not exists citext with schema extensions;

create table public.brands (
  id bigint generated by default as identity (start with 1000000) primary key,
  brand_name text not null,
  sort integer not null default 0,
  created_at timestamptz
);

create unique index brands_name_key on public.brands (lower(brand_name));

create table public.cars (
  id bigint generated by default as identity (start with 1000000) primary key,
  brand_id bigint not null references public.brands(id) on delete restrict,
  code text not null unique,
  name text not null,
  image_path text,
  synopsis text,
  is_show boolean not null default true,
  folder_name text not null check (folder_name ~ '^[A-Za-z0-9._-]+$'),
  manual_id bigint,
  menu_type text,
  sort integer not null default 0,
  created_at timestamptz,
  updated_at timestamptz
);

create index cars_brand_id_idx on public.cars (brand_id);
create index cars_visible_sort_idx on public.cars (sort desc, name) where is_show;
create index cars_manual_id_idx on public.cars (manual_id) where manual_id is not null;

create table public.app_users (
  id bigint generated by default as identity (start with 1000000) primary key,
  email extensions.citext not null unique,
  name text not null,
  password_hash text not null,
  contact_address text,
  auth_code text,
  status boolean not null default true,
  vip_status boolean not null default false,
  vip_expires_at timestamptz,
  role text not null default 'customer' check (role in ('admin', 'customer')),
  created_at timestamptz not null default now()
);

create index app_users_customer_list_idx on public.app_users (id desc) where role = 'customer';

create table public.authorization_codes (
  id bigint generated by default as identity (start with 1000000) primary key,
  code text not null unique,
  duration_hours numeric not null default 0 check (duration_hours >= 0),
  expires_at timestamptz,
  is_used boolean not null default false,
  status boolean not null default true,
  created_at timestamptz
);

create index authorization_codes_available_idx
  on public.authorization_codes (code)
  where status and not is_used;

create table public.manual_menu (
  id bigint generated by default as identity (start with 1000000) primary key,
  car_id bigint not null references public.cars(id) on delete cascade,
  source_menu_id bigint,
  parent_id bigint references public.manual_menu(id) on delete cascade,
  name text not null,
  relative_file text,
  sort integer not null default 0,
  unique (car_id, source_menu_id)
);

create index manual_menu_car_sort_idx on public.manual_menu (car_id, sort, name);
create index manual_menu_parent_id_idx on public.manual_menu (parent_id) where parent_id is not null;

create table public.app_sessions (
  token_hash text primary key,
  user_id bigint not null references public.app_users(id) on delete cascade,
  csrf_token text not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index app_sessions_user_id_idx on public.app_sessions (user_id);
create index app_sessions_expires_at_idx on public.app_sessions (expires_at);

create function public.get_app_session(p_token_hash text)
returns table (
  id bigint,
  email text,
  name text,
  role text,
  csrf_token text
)
language sql
stable
security invoker
set search_path = ''
as $$
  select users.id, users.email::text, users.name, users.role, sessions.csrf_token
  from public.app_sessions as sessions
  join public.app_users as users on users.id = sessions.user_id
  where sessions.token_hash = p_token_hash
    and sessions.expires_at > now()
    and users.status
  limit 1
$$;

create function public.register_app_user(
  p_email text,
  p_name text,
  p_password_hash text,
  p_auth_code text
)
returns bigint
language plpgsql
security invoker
set search_path = ''
as $$
declare
  selected_code_id bigint;
  selected_duration numeric;
  inserted_user_id bigint;
begin
  select codes.id, codes.duration_hours
    into selected_code_id, selected_duration
  from public.authorization_codes as codes
  where codes.code = p_auth_code
    and codes.status
    and not codes.is_used
  for update;

  if selected_code_id is null then
    return null;
  end if;

  insert into public.app_users (
    email, name, password_hash, auth_code, status, vip_status, vip_expires_at, role
  ) values (
    p_email,
    p_name,
    p_password_hash,
    p_auth_code,
    true,
    true,
    case when selected_duration > 0 then now() + (selected_duration * interval '1 hour') else null end,
    'customer'
  )
  returning app_users.id into inserted_user_id;

  update public.authorization_codes
  set is_used = true
  where authorization_codes.id = selected_code_id;

  return inserted_user_id;
end;
$$;

