create table public.contact_requests (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  email text not null check (char_length(email) between 3 and 254),
  request_type text not null check (request_type in ('general', 'privacy', 'copyright')),
  message text not null check (char_length(message) between 10 and 5000),
  status text not null default 'open' check (status in ('open', 'resolved')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz
);

create index contact_requests_status_created_idx
  on public.contact_requests (status, created_at desc);

alter table public.contact_requests enable row level security;
revoke all on table public.contact_requests from anon, authenticated;
grant select, insert, update, delete on table public.contact_requests to service_role;
grant usage, select on sequence public.contact_requests_id_seq to service_role;
